import { describe, expect, it } from 'vitest'
import { compareNames, sortByName } from './sortNames.ts'

describe('compareNames', () => {
  it('한글은 ㄱㄴㄷ 순이고 영문 다음 숫자가 온다', () => {
    const names = [
      '민정',
      '덥덥',
      '곰',
      '단비',
      '씨츠',
      '홍피그',
      '개굴',
      '흰둥이',
      '호두',
      '모스',
      '체리',
      '민준',
      '라디보리',
      '030',
      '연이',
      '코비',
      'WON',
      '비니코코',
      '민성씨',
      '붕어빵',
      '라스',
      '앤텀',
      '윤랑',
      '고니',
      '데일리',
      '강해상',
      '구자',
      '후배',
      '스노우맨',
      '10',
      '2',
    ]

    expect(sortByName(names.map((name) => ({ name }))).map((item) => item.name)).toEqual([
      '강해상',
      '개굴',
      '고니',
      '곰',
      '구자',
      '단비',
      '덥덥',
      '데일리',
      '라디보리',
      '라스',
      '모스',
      '민성씨',
      '민정',
      '민준',
      '붕어빵',
      '비니코코',
      '스노우맨',
      '씨츠',
      '앤텀',
      '연이',
      '윤랑',
      '체리',
      '코비',
      '호두',
      '홍피그',
      '후배',
      '흰둥이',
      'WON',
      '2',
      '10',
      '030',
    ])
  })

  it('같은 값이면 0을 반환한다', () => {
    expect(compareNames('모스', '모스')).toBe(0)
  })
})
